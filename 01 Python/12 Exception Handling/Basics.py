# Exception Handling in Python
# Exceptions are errors that occur during the execution of a program. 
# When an error occurs, Python raises an exception, which can be handled using try-except blocks.

# During Compilation => Syntax Errors
# During Execution => Exceptions

# Syntax Error : 
    # Something in the program is now written according to the program grammar.
    # Error is raised by interpreter/compiler.
# Example : 
# print("Hello World"  # Missing closing parenthesis

# Exception :
    # Something in the program is not written according to the program logic.
    # Exception is raiesed by python runtime.
# Example :
# print(10 / 0)  # Division by zero error



